// DOM-level interaction verification. Not a substitute for browser/visual QA.
// npm install --prefix /tmp/aden-qa --ignore-scripts jsdom
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const { JSDOM } = await import(process.env.JSDOM_MODULE || 'jsdom');
const html = readFileSync('public/kitchen/index.html', 'utf8');
const dom = new JSDOM(html, { runScripts: 'outside-only' });
const { document } = dom.window;
dom.window.eval(html.match(/<script[^>]*>([\s\S]*?)<\/script>/)[1]);
const el = id => document.getElementById(id);
const click = id => el(id).click();
const select = id => document.querySelector(`[data-id="${id}"]`).click();
const step = id => document.querySelector(`[data-step="${id}"]`).click();
click('next');
assert.match(el('feedback').textContent, /exactly five/);
for (const id of ['onion', 'shiro', 'oil', 'water', 'garlic']) select(id);
click('next');
assert.equal(el('points').textContent, '50 practice points');
select('onion'); // Locked pantry cannot be scored repeatedly.
assert.equal(el('points').textContent, '50 practice points');
click('next');
assert.equal(el('next').disabled, true);
for (const id of ['onion', 'oil', 'water', 'shiro', 'simmer']) step(id);
assert.equal(el('points').textContent, '90 practice points');
click('next');
assert.equal(el('next').disabled, true);
click('stir'); click('stir'); click('stir'); click('stir');
assert.equal(el('stir').textContent, 'Stir the pot · 3 / 3');
click('next');
assert.match(el('content').textContent, /Shiro star/);
assert.equal(el('points').textContent, '120 practice points');
assert.match(el('content').textContent, /cannot be redeemed/);
click('next');
assert.equal(el('points').textContent, '0 practice points');
click('challenge');
assert.equal(el('challenge').getAttribute('aria-pressed'), 'true');
for (const id of ['cream', 'sugar', 'pasta', 'water', 'oil']) select(id);
click('next');
assert.equal(el('points').textContent, '0 practice points');
click('next');
step('simmer'); step('simmer'); step('onion');
assert.equal(el('points').textContent, '6 practice points');
for (const id of ['oil', 'water', 'shiro', 'simmer']) step(id);
click('next');
el('heat').value = '100'; el('heat').dispatchEvent(new dom.window.Event('input'));
click('stir'); click('stir'); click('stir'); click('next');
assert.equal(el('points').textContent, '38 practice points');
assert.match(el('content').textContent, /Curious cook/);
click('practice');
assert.equal(el('points').textContent, '0 practice points');
assert.equal(el('practice').getAttribute('aria-pressed'), 'true');
console.log('PASS: DOM interaction: perfect round, wrong choices, repeated actions, challenge, heat penalty, replay/mode reset.');
dom.window.close();
